"""Helpers for the storage performance steps, which drive storage-scale-test on Kubernetes.

storage-scale-test (https://github.com/NVIDIA/storage-scale-test/tree/v2.1.0) runs the benchmark. On
Kubernetes its launcher only submits: the sweep runs in-cluster, ``--status`` reports its
progress, and ``--collect`` copies the results back and releases what the sweep holds (the
claim's Lease, the coordinator Job, the worker DaemonSet and its network policies). These
helpers drive that lifecycle synchronously, so one isvctl step can submit, wait and collect.
"""

