_KV = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$")


class Clock:
    """The time source for waits and lock retries; tests swap in a fake that sleeps instantly."""

    def monotonic(self) -> float:
        """Seconds on a clock that never goes back."""
        return time.monotonic()

    def sleep(self, seconds: float) -> None:
        """Pause for *seconds*."""
        time.sleep(seconds)


CLOCK = Clock()


class ToolError(OSError):
    """A command that could not be started; its message names the file and the likely cause."""


@dataclass(frozen=True)
class Ran:
    """A finished command: exit code, output, and whether our timeout stopped it."""

    returncode: int
    stdout: str
    stderr: str
    timed_out: bool = False


# The storage-scale-test call in flight, for the interrupt handler.
_ACTIVE: subprocess.Popen[str] | None = None


def log(message: str) -> None:
    """Write a progress line to stderr; stdout is reserved for the step's JSON."""
    print(message, file=sys.stderr, flush=True)


def emit(result: dict[str, Any]) -> int:
    """Print the step result as JSON and return the matching exit code."""
    print(json.dumps(result, indent=2))
    return 0 if result.get("success") else 1


def parse_kv(text: str) -> dict[str, str]:
    """Parse ``KEY=value`` lines; storage-scale-test prints its lifecycle state this way.

    It writes diagnostic values and FAILED_LOG with ``printf %q``, so those are unquoted.
    """
    out: dict[str, str] = {}
    for line in text.splitlines():
        match = _KV.match(line.strip())
        if match:
            key, value = match.group(1), match.group(2)
            if key.startswith(DIAGNOSTIC_PREFIX) or key == "FAILED_LOG":
                try:
                    value = " ".join(shlex.split(value))
                except ValueError:
                    pass
            out[key] = value
    return out


def _signal_group(proc: subprocess.Popen[str], sig: signal.Signals) -> None:
    """Signal the process group *proc* leads, if any of it is left."""
    try:
        # macOS refuses to signal a group whose only member is an exited, unreaped leader.
        proc.poll()
        os.killpg(proc.pid, sig)
    except (ProcessLookupError, PermissionError):
        pass


def _stop(proc: subprocess.Popen[str]) -> tuple[str, str]:
    """Stop a timed-out command's process group and return what it printed.

    Bounded at TERM_GRACE_S + DRAIN_S: a leftover outside the group that still holds the
    pipes gets them closed under it instead of being waited for.
    """
    _signal_group(proc, signal.SIGTERM)
    try:
        stdout, stderr = proc.communicate(timeout=TERM_GRACE_S)
    except subprocess.TimeoutExpired:
        _signal_group(proc, signal.SIGKILL)
        try:
            return proc.communicate(timeout=DRAIN_S)
        except subprocess.TimeoutExpired:
            for pipe in (proc.stdout, proc.stderr):
                if pipe is not None:
                    pipe.close()
            proc.wait()
            return "", ""
    # The leader exited; make sure nothing else in its group outlives the call.
    _signal_group(proc, signal.SIGKILL)
    return stdout, stderr


def run(cmd: list[str], timeout: float, env: dict[str, str] | None = None) -> Ran:
    """Run a command in its own session; a timeout comes back as exit code 124 instead of raising.

    A command that cannot be started raises ToolError (an OSError) naming it and the likely cause.

    On timeout the command's whole process group is stopped (TERM, then KILL), so no
    storage-scale-test process outlives the call. It returns within timeout + TERM_GRACE_S +
    DRAIN_S even when a leftover outside the group keeps the pipes open.

    Like isvtest.core.process.run_command_process, but it records the process in _ACTIVE so
    the interrupt handler can kill it within INTERRUPT_GRACE_S, inside isvctl's 2 s.
    """
    global _ACTIVE
    try:
        proc = subprocess.Popen(
            cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, env=env, start_new_session=True
        )
    except OSError as exc:
        if isinstance(exc, PermissionError):
            cause = "it is not executable (chmod +x it) or its directory cannot be read"
        elif isinstance(exc, FileNotFoundError):
            cause = "it (or the interpreter its first line names) does not exist"
        else:
            cause = exc.strerror or str(exc)
        raise ToolError(f"cannot run {cmd[0]}: {cause}") from exc
    # Ctrl-C does not reach this new session; install_interrupt_handler stops the command.
    _ACTIVE = proc
    try:
        try:
            stdout, stderr = proc.communicate(timeout=timeout)
        except subprocess.TimeoutExpired:
            stdout, stderr = _stop(proc)
            return Ran(124, stdout, f"{stderr}\ntimed out after {timeout:.0f}s", True)
        return Ran(proc.returncode, stdout, stderr)
    finally:
        _ACTIVE = None


def install_interrupt_handler(
    progress: ProgressLog | None = None, hint: str | None = TEARDOWN_HINT
) -> Callable[[], None]:
    """On SIGINT or SIGTERM, stop the call in flight and exit 130; returns the restore function.

    isvctl forwards Ctrl-C to the step and kills it 2 s later. Each storage-scale-test call
    runs in its own session and never sees that signal, so without this it would outlive the
    step and hold the sweep directory's lock. The sweep itself is left alone (no cancel), so
    `--phase teardown` can release it afterwards. SIGTERM exits 130 too, so both read as an
    interrupted step.

    The message, with *hint* if given, goes to stderr and to *progress*, if given. isvctl does
    not show an interrupted step's stderr, so the progress log is where a user finds it.
    """

    def handle(signum: int, _frame: Any) -> None:
        """Stop the call in flight, record the interrupt, and exit 130."""
        # Exit whatever happens here: the signal can land inside a stderr write, where print()
        # would raise instead of writing.
        try:
            proc = _ACTIVE
            if proc is not None:
                _signal_group(proc, signal.SIGTERM)
                deadline = time.monotonic() + INTERRUPT_GRACE_S
                while proc.poll() is None and time.monotonic() < deadline:
                    time.sleep(0.05)
                _signal_group(proc, signal.SIGKILL)
            name = signal.Signals(signum).name
            message = f"interrupted ({name})" + (f"; {hint}" if hint else "")
            try:
                os.write(2, (message + "\n").encode())
            except OSError:
                pass
            if progress is not None:
                progress.event(message)
        finally:
            os._exit(130)

    previous = {sig: signal.signal(sig, handle) for sig in (signal.SIGINT, signal.SIGTERM)}

    def restore() -> None:
        """Put back the handlers that were installed before."""
        for sig, handler in previous.items():
            signal.signal(sig, handler)

    return restore


class ProgressLog:
    """A run's progress log, one line per event: ``<UTC>  +<elapsed s>  <event>  key=value ...``.

    isvctl prints nothing from a step that passes, so this file is how to follow a long sweep.
    Callers pass only a few short fields, never command output or credentials.
    """

    def __init__(self, directory: Path) -> None:
        """Start a new log in *directory*, named for the UTC start time and this process."""
        directory.mkdir(parents=True, exist_ok=True)
        self.path = directory / f"run-{datetime.now(UTC):%Y%m%dT%H%M%SZ}-{os.getpid()}.log"
        self.path.touch()
        self.started = CLOCK.monotonic()

    def event(self, name: str, **fields: Any) -> None:
        """Append one line; fields that are None are left out."""
        values = " ".join(f"{key}={value}" for key, value in fields.items() if value is not None)
        line = f"{datetime.now(UTC):%Y-%m-%dT%H:%M:%SZ}  +{CLOCK.monotonic() - self.started:.0f}  {name}  {values}"
        try:
            with self.path.open("a", encoding="utf-8") as out:
                out.write(line.rstrip() + "\n")
        except OSError as exc:
            log(f"cannot write the progress log {self.path}: {exc}")


def diagnostics(stderr: str) -> dict[str, str]:
    """storage-scale-test's ``STORAGE_SCALE_TEST_DIAGNOSTIC_*`` fields, without the prefix."""
    return {
        k.removeprefix(DIAGNOSTIC_PREFIX): v for k, v in parse_kv(stderr).items() if k.startswith(DIAGNOSTIC_PREFIX)
    }


def describe_failure(stderr: str) -> str:
    """storage-scale-test's own explanation of a failed command.

    It prints ``Error: ...`` lines plus ``STORAGE_SCALE_TEST_DIAGNOSTIC_*`` fields to stderr;
    the errors and the diagnostic say why the operation stopped, whether its workload may
    still be running, what to do next, and where it saved the evidence.
    """
    errors = [line[len("Error:") :].strip() for line in stderr.splitlines() if line.startswith("Error:")]
    fields = diagnostics(stderr)
    reason, phase = fields.get("REASON"), fields.get("PHASE")
    detail = ""
    if reason:
        detail = f" ({reason}, phase {phase})" if phase else f" ({reason})"
    # All of them: a failed settings check prints one line per problem, then a generic summary.
    # Without Error: lines, the last line that is not a diagnostic field (those are reported below).
    plain = [line.strip() for line in stderr.splitlines() if line.strip() and not line.startswith(DIAGNOSTIC_PREFIX)]
    message = "; ".join(errors) if errors else (plain or ["no error output"])[-1]
    extra = []
    if fields.get("MAY_STILL_BE_RUNNING") in ("yes", "unknown"):
        extra.append(f"may still be running: {fields['MAY_STILL_BE_RUNNING']}")
    if fields.get("SAFE_NEXT_ACTION"):
        extra.append(f"next: {fields['SAFE_NEXT_ACTION']}")
    if fields.get("PATH"):
        extra.append(f"diagnostics: {fields['PATH']}")
    return message + detail + "".join(f"; {item}" for item in extra)


