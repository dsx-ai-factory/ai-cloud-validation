def test_dirs(claim: str) -> str:
    """The TEST_DIRS assignment for *claim* (namespace/claim): its scale-test directory, weight 1."""
    return f"TEST_DIRS=([{bash_quote(f'{claim}:{TEST_PATH}')}]=1)"


def bash_quote(value: str) -> str:
    """Single-quote a value for Bash."""
    return "'" + value.replace("'", "'\\''") + "'"


def bash_array(values: list[str]) -> str:
    """A Bash indexed-array literal."""
    return "(" + " ".join(bash_quote(v) for v in values) + ")"


def try_lock(path: Path) -> int | None:
    """Take an exclusive lock on *path* without waiting; the descriptor holding it, or None if held.

    Closing the descriptor (unlock) or exiting releases it, so it never goes stale, and child
    processes do not inherit it. The file is never removed: removing it would race a process
    that has just opened it.
    """
    fd = os.open(path, os.O_RDWR | os.O_CREAT, 0o644)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        os.close(fd)
        return None
    return fd


def unlock(fd: int) -> None:
    """Release a lock try_lock took."""
    os.close(fd)


def run_lock(results_root: str) -> int | None:
    """Lock the results root, which must exist, for this step (see try_lock).

    One run or teardown at a time per results root.
    """
    return try_lock(Path(results_root) / RUN_LOCK)


def checkout_lock(base: Path, wait_s: float) -> int | None:
    """Lock the checkout's env.sh and submit, waiting up to *wait_s* for another run's submit."""
    deadline = CLOCK.monotonic() + wait_s
    while (fd := try_lock(base / CHECKOUT_LOCK)) is None:
        if CLOCK.monotonic() >= deadline:
            return None
        CLOCK.sleep(LOCK_RETRY_INTERVAL_S)
    return fd


def unreleased(base: Path, results_root: str, env: dict[str, str]) -> list[tuple[str, str, dict[str, str]]]:
    """The sweeps under *results_root* that may still hold cluster resources, oldest first.

    Each is ``(sweep_dir, kind, status)`` from query(). storage-scale-test keeps every sweep's
    lifecycle in its own sweep directory, so the results root alone says what to release:
    - no kubernetes/current-attempt: submit stopped before it created anything;
    - collected (RESULT_COLLECTION=COMPLETE): released;
    - rolled back (SUBMISSION_FAILED): released. A successful --status reports it as STATE (and
      first finishes rolling back a submit that died part-way). A failed one reports the state
      on disk as DIAGNOSTIC_LOCAL_STATE: --status checks the claim before it answers, so it
      fails once the claim was deleted or replaced, yet the rollback had finished;
    - anything else (running, finished but not collected, a cancel in progress, or no readable
      status): may still hold the claim's Lease, the Job and the workers.

    The teardown step releases each one it returns.
    """
    found = []
    # iterdir, not glob: glob hides a directory it cannot list, which would read as nothing held.
    # Oldest first by the UTC datestamp both kinds of directory end with (elbencho-<ds>,
    # filesystem-batch-<ds>), so plain sweeps and batches interleave in the order they ran.
    held = (p for p in Path(results_root).iterdir() if p.name.startswith(SWEEP_PREFIXES))
    for path in sorted(held, key=lambda p: (p.name.rsplit("-", 1)[-1], p.name)):
        if not (path / CURRENT_ATTEMPT).is_file():
            continue
        kind, status = query(base, str(path), env, lock_window_s=LOCK_WINDOW_S)
        collected = kind == "ok" and status.get("RESULT_COLLECTION") == COLLECTION_COMPLETE
        state = status.get("STATE") if kind == "ok" else status.get("DIAGNOSTIC_LOCAL_STATE")
        rolled_back = state == SUBMISSION_FAILED
        if not (collected or rolled_back):
            found.append((str(path), kind, status))
    return found
