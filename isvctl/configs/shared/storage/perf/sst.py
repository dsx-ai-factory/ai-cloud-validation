def lifecycle(
    base: Path, operation: str, sweep_dir: str, env: dict[str, str], *, timeout_s: float, lock_window_s: float
) -> Ran:
    """Run ``--status``, ``--cancel`` or ``--collect``, retrying while the lock is busy.

    A refused command is retried every LOCK_RETRY_INTERVAL_S until *lock_window_s* has passed.
    """
    started = CLOCK.monotonic()
    while True:
        ran = run([str(base / LAUNCHER), operation, sweep_dir], timeout_s, env)
        if LOCK_BUSY not in ran.stderr or CLOCK.monotonic() - started >= lock_window_s:
            return ran
        log(f"{operation}: another lifecycle command holds the lock; retrying")
        CLOCK.sleep(LOCK_RETRY_INTERVAL_S)


def classify(ran: Ran) -> tuple[str, dict[str, str]]:
    """Classify a ``--status`` reply, and return it with the keys it printed.

    - ``ok``: the reply carries the sweep's state (NEXT_ACTION).
    - ``unreachable``: the cluster could not be reached or refused us (REASONS_ACCESS), or our
      status timeout stopped the call.
    - ``failed``: anything else; the cluster answered, but not with the sweep's state.

    A failed reply still carries DIAGNOSTIC_REASON and DIAGNOSTIC_LOCAL_STATE, the state
    storage-scale-test has on disk for the sweep, when it printed them.
    """
    fields = parse_kv(ran.stdout)
    diagnostic = diagnostics(ran.stderr)
    reason = diagnostic.get("REASON", "")
    for key in ("REASON", "LOCAL_STATE"):
        if diagnostic.get(key):
            fields[f"DIAGNOSTIC_{key}"] = diagnostic[key]
    # --status reports an incomplete cancel with exit 1. Another reason with the same shape
    # (LEDGER_INCONSISTENT) is not a state to trust.
    incomplete_cancel = (
        ran.returncode == 1 and fields.get("STATE") == CANCEL_REQUESTED and reason in ("", CANCELLATION_INCOMPLETE)
    )
    if fields.get("NEXT_ACTION") and (ran.returncode == 0 or incomplete_cancel):
        return "ok", fields
    return ("unreachable" if ran.timed_out or reason in REASONS_ACCESS else "failed"), fields


def query(
    base: Path,
    sweep_dir: str,
    env: dict[str, str],
    *,
    timeout_s: float = STATUS_TIMEOUT_S,
    lock_window_s: float = POLL_LOCK_WINDOW_S,
) -> tuple[str, dict[str, str]]:
    """Ask storage-scale-test for the sweep's state; returns classify()'s ``(kind, fields)``.

    Only ``ok`` describes the sweep: a failed query is not evidence that the sweep failed.
    """
    ran = lifecycle(base, "--status", sweep_dir, env, timeout_s=timeout_s, lock_window_s=lock_window_s)
    kind, fields = classify(ran)
    if kind != "ok":
        log(f"--status: {kind}, exit {ran.returncode}: {ran.stderr.strip()[-500:]}")
    return kind, fields


def count_node_counts(spec: str) -> int:
    """How many node counts a ``--nodes`` spec (``X``, ``X-Y``, ``X-Y+Z``, comma lists) sweeps.

    0 for a spec this step cannot read, such as ``all``: storage-scale-test rejects those
    itself, before it touches the cluster. Like storage-scale-test, a range
    always includes its start and its end: ``1-10+4`` is 1, 5, 9, 10, so 4. Counted without
    listing them, so a huge spec costs nothing.
    """
    total = 0
    for element in spec.split(","):
        match = re.fullmatch(r"(\d+)(?:-(\d+)(?:\+(\d+))?)?", element.strip())
        if not match:
            return 0
        start = int(match.group(1))
        stop = int(match.group(2) or start)
        step = int(match.group(3) or 1)
        if start < 1 or stop < start or step < 1:
            return 0
        total += len(range(start, stop, step)) + 1
    return total


def count_cells(nodes: str, io_sizes: list[str], threads: list[str], iodepths: list[str]) -> int:
    """Count the sweep's cells (node counts x IO sizes x threads x IO depths)."""
    return count_node_counts(nodes) * len(io_sizes) * len(threads) * len(iodepths)


def estimate_s(groups: list[tuple[int, int]]) -> int:
    """Seconds from submit until the run notices a sweep has finished.

    *groups* is ``(cells, phase duration in seconds)`` per group: one for a plain sweep, one per
    group of a batch. A batch's groups run back to back in one attempt, so it pays the fixed
    overhead once.
    """
    return FIXED_OVERHEAD_S + sum(cells * (2 * duration_s + PER_CELL_OVERHEAD_S) for cells, duration_s in groups)


def auto_wait_s(estimate: int) -> int:
    """The automatic wait for a sweep estimated at *estimate* seconds, between WAIT_FLOOR_S and WAIT_CAP_S."""
    return min(WAIT_CAP_S, max(WAIT_FLOOR_S, int(SAFETY * estimate)))


def wait_for_terminal(
    base: Path, sweep_dir: str, env: dict[str, str], *, deadline_s: float, progress: ProgressLog | None = None
) -> tuple[bool, dict[str, str]]:
    """Poll ``--status`` every POLL_INTERVAL_S until the sweep is past WAIT or *deadline_s* passes.

    Returns ``(finished, status)``. Finished means the last status's NEXT_ACTION is not WAIT:
    COLLECT for a finished sweep, INSPECT for a rolled-back submission or a pending cancel. A
    poll with no readable status (the cluster is out of reach, say) just waits for the next one:
    the sweep runs on in-cluster. *status* is the last readable one.
    """
    start = CLOCK.monotonic()
    last: dict[str, str] = {}
    polls = 0
    while True:
        polls += 1
        kind, fields = query(base, sweep_dir, env)
        if progress is not None:
            progress.event(
                "poll",
                n=polls,
                kind=kind,
                state=fields.get("STATE"),
                next_action=fields.get("NEXT_ACTION"),
                done=fields.get("EXECUTIONS_SUCCEEDED"),
                total=fields.get("EXECUTIONS_TOTAL"),
                reason=fields.get("DIAGNOSTIC_REASON"),
            )
        if kind == "ok":
            last = fields
            if fields.get("NEXT_ACTION") != NEXT_WAIT:
                return True, fields
            done, total = fields.get("EXECUTIONS_SUCCEEDED", "?"), fields.get("EXECUTIONS_TOTAL", "?")
            log(f"sweep {fields.get('STATE')}: {done}/{total} done")
        remaining = deadline_s - (CLOCK.monotonic() - start)
        if remaining <= 0:
            return False, last
        # Never sleep past the deadline, so the cancel is not up to a poll interval late.
        CLOCK.sleep(min(POLL_INTERVAL_S, remaining))


def collect(base: Path, sweep_dir: str, env: dict[str, str], *, progress: ProgressLog | None = None) -> dict[str, Any]:
    """Run ``--collect`` until the sweep's cluster resources are released (COLLECT_ATTEMPTS tries).

    ``--collect`` exits nonzero for a FAILED or CANCELLED attempt even after publishing the
    cells that finished, so its exit code alone does not say whether collection worked;
    ``RESULT_COLLECTION=COMPLETE`` does. A collect can publish the results yet leave cleanup
    pending (``NEXT_ACTION=COLLECT``); storage-scale-test's answer is to collect again.

    ``final_status`` holds the last status that confirmed an attempt, so callers need not ask
    again. Collect refuses a running sweep, so callers cancel one first (see cancel).
    """
    collect_env = {**env, COLLECT_DEADLINE_ENV: str(COLLECT_DEADLINE_S)}
    out: dict[str, Any] = {"resources_released": False}
    kind, status = "", {}
    for attempt in range(1, COLLECT_ATTEMPTS + 1):
        ran = lifecycle(
            base, "--collect", sweep_dir, collect_env, timeout_s=COLLECT_TIMEOUT_S, lock_window_s=LOCK_WINDOW_S
        )
        failed = {k: v for k, v in parse_kv(ran.stdout).items() if k in ("FAILED_EXECUTION", "FAILED_LOG") and v}
        out.update({k.lower(): v for k, v in failed.items()})
        kind, status = query(base, sweep_dir, env, lock_window_s=LOCK_WINDOW_S)
        if progress is not None:
            progress.event(
                "collect", attempt=attempt, rc=ran.returncode, result_collection=status.get("RESULT_COLLECTION")
            )
        if kind != "ok":
            continue
        out["final_status"] = status
        if status.get("RESULT_COLLECTION") == COLLECTION_COMPLETE:
            out["resources_released"] = True
            return out
        if status.get("NEXT_ACTION") != NEXT_COLLECT:
            break
        log(f"collect {attempt}: cleanup still pending (RESULT_COLLECTION={status.get('RESULT_COLLECTION')})")
    launcher = base / LAUNCHER
    if kind != "ok":
        out["collect_error"] = (
            "could not confirm that collect released the sweep's cluster resources (its status could not be "
            f"read); run `{launcher} --status {sweep_dir}`, and `--collect` if it still holds them"
        )
    else:
        out["collect_error"] = (
            f"the sweep still holds cluster resources (RESULT_COLLECTION={status.get('RESULT_COLLECTION')}); "
            f"run `{launcher} --collect {sweep_dir}` to release them"
        )
    return out


def cancel(
    base: Path, sweep_dir: str, env: dict[str, str], *, progress: ProgressLog | None = None
) -> dict[str, str] | None:
    """Stop a running sweep; its status once it can be collected, else None.

    Cancel is two-phase: it can leave the attempt in CANCEL_REQUESTED, and the documented
    response is to cancel again (up to CANCEL_ATTEMPTS times). Cancelling does not release
    anything; collect does. A sweep that finished before the cancel reached it keeps its state
    (SUCCESS, for example). On None, callers skip collect, which would refuse a running sweep,
    and report cancel_failed().
    """
    for attempt in range(1, CANCEL_ATTEMPTS + 1):
        ran = lifecycle(base, "--cancel", sweep_dir, env, timeout_s=COMMAND_TIMEOUT_S, lock_window_s=LOCK_WINDOW_S)
        kind, status = query(base, sweep_dir, env, lock_window_s=LOCK_WINDOW_S)
        if progress is not None:
            progress.event("cancel", attempt=attempt, rc=ran.returncode, state=status.get("STATE"))
        if kind == "ok" and status.get("STATE") != CANCEL_REQUESTED and status.get("NEXT_ACTION") != NEXT_WAIT:
            return status
    return None


def cancel_failed(base: Path, sweep_dir: str) -> str:
    """The error for a sweep that cancel() could not stop: it still holds the claim."""
    launcher = base / LAUNCHER
    return (
        f"cancel did not stop the sweep; it may still be running and holds the claim. Run "
        f"`{launcher} --cancel {sweep_dir}` until it reports the sweep stopped, then "
        f"`{launcher} --collect {sweep_dir}`, or rerun `--phase teardown` to retry both"
    )


def compose_env_sh(template: str, settings: list[str]) -> str:
    """Insert isvctl's settings into env.sh.template at its integration-overrides anchor."""
    lines = template.splitlines(keepends=True)
    anchors = [index for index, line in enumerate(lines) if line.strip() == OVERRIDES_ANCHOR]
    if len(anchors) != 1:
        raise ValueError(
            f"{ENV_TEMPLATE} has {len(anchors)} {OVERRIDES_ANCHOR!r} lines, not one; "
            "this storage-scale-test version is not supported"
        )
    block = [GENERATED_MARKER + "\n", *(s + "\n" for s in settings), "\n"]
    return "".join(lines[: anchors[0]] + block + lines[anchors[0] :])


def install_env_sh(base: Path, settings: list[str]) -> Path:
    """Write the checkout's env.sh, refusing to replace one isvctl did not write."""
    path = base / ENV_SH
    if path.is_symlink() or (
        path.exists() and GENERATED_MARKER not in path.read_text(encoding="utf-8", errors="replace")
    ):
        raise FileExistsError(
            f"{path} exists and was not written by isvctl. Point --scale-test-base at a checkout "
            "used only by isvctl, or move that env.sh aside."
        )
    text = compose_env_sh((base / ENV_TEMPLATE).read_text(encoding="utf-8"), settings)
    tmp = path.with_name(ENV_SH + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)
    return path


